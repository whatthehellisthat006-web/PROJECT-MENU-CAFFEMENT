export const featuredProducts = categories.flatMap(category =>
  category.products
    .filter(p => p.featured)
    .map(p => ({ ...p, categoryId: category.id, categoryName: category.name }))
);

export const formatPrice = prices => {
  if (!prices || prices.length === 0 || !prices[0].value) return 'Sur demande';
  if (prices.length > 1) {
    return prices
      .map(p => `${p.label === 'Sur Place' ? 'SP' : 'EMP'} ${p.value} DT`)
      .join(' · ');
  }
  return `${prices[0].value} DT`;
};
